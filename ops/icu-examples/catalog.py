def doc(title, sections, links=()):
    def p(text): return {'type':'paragraph','content':[{'type':'text','text':text}]}
    nodes=[{'type':'heading','attrs':{'level':1},'content':[{'type':'text','text':title}]},p(NOTICE)]
    for heading, paragraphs in sections:
        nodes.append({'type':'heading','attrs':{'level':2},'content':[{'type':'text','text':heading}]})
        nodes.extend(p(text) for text in paragraphs)
    for label,url in links:
        nodes.append({'type':'paragraph','content':[{'type':'text','text':label,'marks':[{'type':'link','attrs':{'href':url,'target':'_blank','rel':'noopener noreferrer'}}]}]})
    return {'type':'doc','content':nodes}
